import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { pathToFileURL } from 'node:url'
const { installation } = await import(pathToFileURL(process.cwd() + '/tests/api/harness.mjs'))
const h = await installation()
try {
  await h.command('business.save', { name: 'Synthetic Glove branch replay', currency: 'USD', timezone: 'America/Chicago', paymentTermsDays: 14 })
  const office = await h.person('Synthetic Glove Office', 'office')
  const customer = await h.command('customer.save', { name: 'Synthetic Glove PO customer', requirePo: true })
  const site = await h.command('site.save', { customerId: customer.id, address: '120 Main Street, Austin TX 78701' })
  const tech = await h.command('technician.save', { name: 'Synthetic Glove technician' })
  const clock = async at => assert.equal((await h.request('/__test/clock', { method: 'POST', body: { at } })).status, 200)
  await clock('2025-01-01T16:00:00Z')
  let job = await h.command('job.create', { customerId: customer.id, siteId: site.id, title: 'Synthetic Glove monthly PM', lines: [{ description: 'Maintenance', quantity: '1', unitPrice: '240.00', tax: 'FREE' }] })
  job = await h.command('series.create', { jobId: job.id, version: job.version, date: '2025-01-01', rule: { unit: 'month' }, technicianId: tech.id, start: '09:00', end: '10:00', until: '2025-01-31', horizonDays: 31, billing: { mode: 'fixed-monthly', lines: [{ description: 'Maintenance', quantity: '1', unitPrice: '240.00', tax: 'FREE' }], autoApprove: true } })
  await clock('2025-01-31T18:00:00Z')
  await h.scheduled('2025-01-31T18:00:00Z')
  const invoice = (await h.state()).invoices.find(i => i.jobId === job.id)
  assert.equal(invoice.status, 'draft')
  assert.equal(invoice.autoApprovalRefused.code, 'PO_REQUIRED')
  const commandId = randomUUID(), result = await office.run('series.billingRun', {}, { commandId })
  assert.deepEqual(await office.run('series.billingRun', {}, { commandId }), result)
  await h.command('branch.limit', { operatorId: office.id, branchId: 'main' })
  assert.deepEqual(await office.run('series.billingRun', {}, { commandId }), result)
  const branch = await h.command('branch.save', { name: 'Synthetic Glove other branch', prefix: 'OTH', timezone: 'America/Chicago', zips: [] })
  await h.command('branch.limit', { operatorId: office.id, branchId: branch.id })
  assert.deepEqual((await office.run('series.billingRun', {})).missed, [])
  const before = await h.request('/api/glove/export').then(r => r.json())
  const replay = async () => {
    const response = await h.request('/api/glove/commands', { method: 'POST', as: office.cookie, body: { commandId, type: 'series.billingRun', payload: {} } })
    const body = await response.json()
    const encoded = JSON.stringify(body)
    const leaked = [job.id, job.number, invoice.id, invoice.number, invoice.autoApprovalRefused.code, invoice.autoApprovalRefused.message].some(value => encoded.includes(value))
    console.log(JSON.stringify({ probe: 'B', door: 'POST /api/glove/commands', operation: 'series.billingRun replay after branch restriction', status: response.status, code: body.error?.code ?? null, leaked, reviewRows: body.result?.missed?.length ?? null }))
    assert.equal(leaked, false, 'branch-restricted replay exposes hidden invoice identity or PO diagnostic')
    assert.ok(response.status === 200 || response.status === 404)
    if (response.status === 200) assert.deepEqual(body.result.missed, [])
    else assert.equal(body.error.code, 'NOT_FOUND')
  }
  await replay()
  const after = await h.request('/api/glove/export').then(r => r.json())
  delete before.exportedAt; delete after.exportedAt
  assert.deepEqual(after, before, 'replay has no record or Activity effect')
  await h.restart(); await clock('2025-01-31T18:00:00Z')
  await replay()
  await h.command('branch.limit', { operatorId: office.id, branchId: null })
  assert.deepEqual(await office.run('series.billingRun', {}, { commandId }), result)
  console.log('PROBE B PASS: hidden replay refused or empty; current-branch replay unchanged; authority restoration retains original result; Worker restart preserves privacy; no replay writes.')
} finally { await h.close() }
