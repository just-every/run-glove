import assert from 'node:assert/strict'
import { installation, business, assertTrail } from './harness.mjs'

export async function voiceFlow(t, inspect = null) {
  const h = await installation({ at: '2030-03-10T10:00:00.000Z' }); t.after(() => h.close())
  const b = await business(h, { currency: 'USD', timezone: 'UTC' })
  let customer = await h.command('customer.save', { ...(await h.state()).customers.find(c => c.id === b.customer.id), phone: '+13125550123' })
  const { accountSid, authToken, fromNumber } = h.twilio
  await h.command('sms.connect', { provider: 'twilio', version: (await h.state()).business[0].version, accountSid, authToken, fromNumber, registration: 'a2p10dlc', registered: true, live: true })
  const config = values => h.command('voice.configure', { version: undefined, ...values })
  const post = async request => h.mf.dispatchFetch(request.url, { method: request.method, headers: Object.fromEntries(request.headers), body: await request.text() })
  const voice = value => h.twilio.voice(h.origin, value)
  const sid = async request => new URLSearchParams(await request.clone().text()).get('CallSid')
  const next = response => { const match = /action="([^"]+)"/.exec(response); assert.ok(match, response); return match[1].replaceAll('&amp;', '&') }
  const destinations = ['+13125550201', '+13125550202'], forward = '+13125550203'
  const settings = async values => config({ version: (await h.state()).business[0].version, enabled: true, approved: true, phones: destinations, forward, ...values })
  let response = await post(voice(1))
  assert.equal(await response.text(), '<Response><Hangup/></Response>', 'voice is off on connection')
  for (const person of [b.office, b.dispatcher, b.agent, b.priyaPerson]) await person.run('voice.configure', {}, { error: 'FORBIDDEN' })
  assert.equal((await h.request('/api/glove/commands', { as: '', method: 'POST', body: { commandId: 'synthetic-glove-signedout', type: 'voice.configure', payload: {} } })).status, 401)
  await h.command('voice.configure', { version: (await h.state()).business[0].version, enabled: true, phones: destinations }, { error: 'CONSENT' })
  await h.command('voice.configure', { version: (await h.state()).business[0].version, enabled: true, approved: true, phones: destinations, recording: true }, { error: 'RECORDING_POLICY' })
  const configured = await settings()
  assert.equal(configured.voice.recording, false)
  const secondOwner = await h.person('Synthetic Second Owner', 'owner')
  const ownerLimit = async limited => h.command('branch.limit', { operatorId: secondOwner.id, branchId: limited ? 'main' : null })
  const token = await h.command('token.issue', { name: 'Synthetic voice probe', role: 'office' })
  assert.equal((await h.request('/api/glove/commands', { as: '', method: 'POST', headers: { authorization: `Bearer ${token.token}` }, body: { commandId: 'synthetic-glove-token', type: 'voice.configure', payload: {} } })).status, 403)
  const custom = await h.command('role.save', { name: 'Synthetic desk', permissions: ['conversation.log'] })
  const customPerson = await h.person('Synthetic Desk', `custom:${custom.id}`)
  await customPerson.run('voice.configure', {}, { error: 'FORBIDDEN' })
  const forged = voice(2); forged.headers.set('x-twilio-signature', 'invalid')
  const before = (await h.state()).version
  assert.equal((await post(forged)).status, 401)
  assert.equal((await post(h.twilio.voice(h.origin, 2, { AccountSid: 'synthetic-glove-foreign' }))).status, 401)
  assert.equal((await h.state()).version, before, 'unauthenticated callbacks write nothing')
  const answered = voice(2), answeredSid = await sid(answered)
  const concurrent = await Promise.all([post(answered.clone()), post(answered.clone())])
  assert.deepEqual(concurrent.map(r => r.status), [200, 200])
  response = concurrent[0]
  let twiml = await response.text()
  assert.match(twiml, /<Number>\+13125550201<\/Number>/)
  assert.ok(!twiml.includes('record='), 'recording is never requested')
  assert.equal(await (await post(answered.clone())).text(), twiml)
  const answer = h.twilio.dial(next(twiml), answeredSid, 'completed', '83')
  assert.equal(await (await post(answer.clone())).text(), '<Response><Hangup/></Response>')
  assert.equal((await post(answer.clone())).status, 200)
  await h.request('/__test/clock', { method: 'POST', body: { at: '2030-03-10T10:01:00.000Z' } })
  const missed = voice(3), missedSid = await sid(missed)
  twiml = await (await post(voice(3))).text()
  for (const [index, number] of [...destinations, forward].entries()) {
    assert.match(twiml, new RegExp(`<Number>\\${number}</Number>`))
    twiml = await (await post(h.twilio.dial(next(twiml), missedSid, ['busy', 'no-answer', 'failed'][index]))).text()
  }
  assert.equal(twiml, '<Response><Hangup/></Response>')
  let calls = (await h.state()).conversations.filter(c => c.provider === 'twilio')
  assert.deepEqual(calls.map(c => [c.providerCallId, c.caller, c.outcome, c.durationSeconds, c.recording, c.recordingNotice]).sort(), [[answeredSid, '+13125550123', 'answered', 83, null, 'Not recorded'], [missedSid, '+13125550123', 'missed', 0, null, 'Not recorded']].sort())
  assert.equal(h.twilio.messages.size, 0, 'missed webhooks never automatically text')
  const call = calls.find(c => c.outcome === 'missed')
  const service = await h.command('service.save', { ...b.service, tax: 'FREE', unitPrice: '100.00' })
  const job = await h.command('job.create', { customerId: customer.id, siteId: b.site.id, serviceId: service.id, title: 'Missed-call service', lines: [{ serviceId: service.id, description: service.name, unitPrice: '100.00', quantity: '1', tax: 'FREE' }] })
  const offer = await h.command('booking.offer', { jobId: job.id, slots: [{ date: '2030-03-12', start: '10:00', end: '11:00', window: { start: '10:00', end: '11:00' } }] })
  const reply = { callId: call.id, version: call.version, offerId: offer.id, token: offer.token }
  await b.office.run('voice.textBack', reply, { error: 'FORBIDDEN' })
  await h.command('voice.textBack', { ...reply, callId: calls.find(c => c.outcome === 'answered').id, version: calls.find(c => c.outcome === 'answered').version }, { error: 'CALL_STATE' })
  await h.command('sms.configure', { version: (await h.state()).business[0].version, enabled: true, approved: true })
  await h.command('voice.textBack', reply, { error: 'SMS_CONSENT' })
  customer = (await h.state()).customers.find(c => c.id === customer.id)
  await h.command('sms.consent', { customerId: customer.id, version: customer.version, purpose: 'missedCalls', enabled: true, address: customer.phone, source: 'Customer asked the Owner in person', wording: 'Text one booking reply after a missed call. STOP ends texts.', timezone: 'UTC' })
  await h.request('/__test/clock', { method: 'POST', body: { at: '2030-03-10T20:00:00.000Z' } })
  const quiet = await h.command('voice.textBack', reply, { error: 'SMS_CONSENT' }); assert.equal(quiet.details.reason, 'quiet_hours')
  assert.equal(h.twilio.messages.size, 0)
  await h.request('/__test/clock', { method: 'POST', body: { at: '2030-03-11T10:00:00.000Z' } })
  const commandId = 'synthetic-glove-voice-text'
  await h.command('voice.textBack', reply, { commandId })
  await h.command('voice.textBack', reply, { commandId })
  assert.equal(h.twilio.messages.size, 1)
  const message = [...h.twilio.messages.values()][0]
  assert.equal(message.to, customer.phone)
  assert.equal(message.body, `Sorry we missed your call. Choose a service time: ${h.origin}/book#token=${offer.token}\n\nHarbour Air & Electrical\nReply STOP to stop texts, HELP for help, START to request texts again.`)
  let state = await h.state(), sms = state.messages.find(m => m.voiceCallId === call.id)
  assert.equal(state.messageStates[sms.id].status, 'accepted')
  assert.equal((await post(h.twilio.delivery(message.sid))).status, 200)
  state = await h.state(); assert.equal(state.messageStates[sms.id].status, 'delivered')
  const history = await (await h.request(`/api/glove/sites/${b.site.id}/history`)).json()
  assert.ok(history.entries.some(e => e.id === `sms:${sms.id}` && e.kind === 'message'), 'the booking reply enters property history')
  await h.command('voice.textBack', { ...reply, version: state.conversations.find(c => c.id === call.id).version }, { error: 'CALL_STATE' })
  const stream = (await (await h.request(`/api/glove/conversation?customerId=${customer.id}`)).json()).entries
  assert.deepEqual(stream.map(e => [e.direction, e.channel, e.author]), [['inbound', 'business phone', customer.name], ['inbound', 'business phone', customer.name], ['outbound', 'text message', 'Olivia Owner']])
  assert.deepEqual(stream.map(e => e.at), stream.map(e => e.at).sort())
  assert.match(stream[0].delivery, /answered, 83 seconds · Not recorded/)
  for (const person of [b.office, b.dispatcher, b.agent, customPerson]) {
    assert.equal((await person.state()).conversations.filter(c => c.provider === 'twilio').length, 0)
    assert.equal((await person.state()).events.filter(e => e.kind.startsWith('voice.')).length, 0)
    for (const path of ['/api/glove/state', '/api/glove/export']) {
      const response = await h.request(path, { as: person.cookie })
      if (path === '/api/glove/export' && person !== b.office) { assert.equal(response.status, 403); continue }
      assert.equal(response.status, 200)
      const visible = await response.json()
      const reply = visible.messages.find(m => m.id === sms.id)
      if (person === b.office || person === b.dispatcher) assert.ok(reply, 'ordinary text history remains available to the desk')
      assert.ok(!JSON.stringify(visible).includes(call.id), `${person.id} cannot read the native call identity through ${path}`)
      if (reply) {
        assert.equal(reply.voiceCallId, undefined, 'native call references remain Owner-only')
        assert.equal(reply.bookingOfferId, undefined, 'the call-to-offer association remains Owner-only')
      }
    }
    assert.equal((await (await h.request(`/api/glove/conversation?customerId=${customer.id}`, { as: person.cookie })).json()).entries.filter(e => e.channel === 'business phone').length, 0)
  }
  const { activity, exported } = await assertTrail(h, ['voice.configure', 'voice.received', 'voice.answered', 'voice.routeFailed', 'voice.missed', 'voice.textBack', 'sms.queued', 'sms.accepted', 'sms.delivered'])
  for (const providerCallId of [answeredSid, missedSid]) assert.ok(activity.some(e => e.summary.includes(providerCallId)))
  assert.equal(exported.conversations.filter(c => c.provider === 'twilio').length, 2)
  assert.ok(!JSON.stringify(exported).includes(authToken))
  assert.ok(!JSON.stringify(exported).includes(offer.token))
  if (inspect) await inspect(h, b)
  // A previously authorized leg keeps its actual result after routing is withdrawn.
  const inFlight = voice(4), inFlightSid = await sid(inFlight)
  const inFlightRoute = next(await (await post(inFlight.clone())).text())
  await h.command('voice.configure', { version: (await h.state()).business[0].version, enabled: false })
  assert.equal(await (await post(h.twilio.dial(inFlightRoute, inFlightSid, 'completed', '19'))).text(), '<Response><Hangup/></Response>')
  assert.equal((await h.state()).conversations.find(c => c.providerCallId === inFlightSid).durationSeconds, 19)
  assert.equal((await h.state()).conversations.find(c => c.providerCallId === inFlightSid).outcome, 'answered')
  await settings()
  const stoppedCall = voice(5), stoppedSid = await sid(stoppedCall)
  twiml = await (await post(stoppedCall.clone())).text()
  for (let index = 0; index < 3; index++) twiml = await (await post(h.twilio.dial(next(twiml), stoppedSid))).text()
  assert.equal(twiml, '<Response><Hangup/></Response>')
  assert.equal((await post(h.twilio.inbound(h.origin, customer.phone, 'STOP'))).status, 200)
  const stopped = (await h.state()).conversations.find(c => c.providerCallId === stoppedSid)
  await h.command('voice.textBack', { ...reply, callId: stopped.id, version: stopped.version }, { error: 'SMS_CONSENT' })
  assert.equal(h.twilio.messages.size, 1, 'STOP refuses a later missed-call reply')
  assert.equal(await (await post(h.twilio.voice(h.origin, 6, { From: '+13125550999' }))).text(), '<Response><Hangup/></Response>', 'unknown callers remain outside this preparatory slice')
  await secondOwner.run('voice.configure', { version: (await h.state()).business[0].version, enabled: true, approved: true, phones: destinations, forward })
  await ownerLimit(true)
  await secondOwner.run('voice.configure', {}, { error: 'FORBIDDEN' })
  assert.equal((await secondOwner.state()).conversations.filter(c => c.provider === 'twilio').length, 0)
  assert.equal(await (await post(voice(7))).text(), '<Response><Hangup/></Response>')
  await ownerLimit(false)
  await settings()
  // A valid signature cannot restore routing after the caller's current identity changes.
  const changedCall = voice(8), changedSid = await sid(changedCall)
  const initial = await (await post(changedCall.clone())).text()
  assert.match(initial, /<Dial /)
  const firstLeg = h.twilio.dial(next(initial), changedSid, 'busy')
  const secondRoute = await (await post(firstLeg.clone())).text()
  assert.match(secondRoute, /<Dial /)
  const ringingCall = voice(9)
  assert.match(await (await post(ringingCall.clone())).text(), /<Dial /)
  customer = (await h.state()).customers.find(c => c.id === customer.id)
  customer = await h.command('customer.save', { ...customer, phone: '+13125550888' })
  const changedVersion = (await h.state()).version
  for (const replay of [ringingCall, changedCall, firstLeg]) {
    assert.equal(await (await post(replay.clone())).text(), '<Response><Hangup/></Response>', 'changed-number signed replay cannot dial')
  }
  assert.equal(await (await post(h.twilio.dial(next(secondRoute), changedSid, 'busy'))).text(), '<Response><Hangup/></Response>', 'fresh callback cannot dial the next destination for a changed number')
  assert.equal((await h.state()).version, changedVersion, 'refused routing writes nothing')
  customer = await h.command('customer.save', { ...customer, phone: '+13125550123' })
  // Erasure removes calls, replies, saved outcomes and provider references; retries cannot revive them.
  customer = (await h.state()).customers.find(c => c.id === customer.id)
  const preview = await h.command('privacy.preview', { customerId: customer.id, version: customer.version })
  await h.command('privacy.erase', { customerId: customer.id, version: customer.version, confirm: 'ERASE', fingerprint: preview.fingerprint })
  const erased = await (await h.request('/api/glove/export')).json()
  assert.equal(erased.conversations.length, 0)
  assert.ok(!JSON.stringify(erased).includes(missedSid))
  assert.equal(await (await post(voice(3))).text(), '<Response><Hangup/></Response>')
  assert.equal((await h.state()).conversations.length, 0)
  await h.command('customer.save', { name: 'Synthetic replacement customer', phone: '+13125550123' })
  assert.equal(await (await post(voice(3))).text(), '<Response><Hangup/></Response>', 'a reused number cannot revive an erased call under a new customer')
  assert.equal((await h.state()).conversations.length, 0)
}
