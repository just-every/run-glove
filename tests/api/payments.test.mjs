  h.stripePayments.status = 200
  h.stripePayments.refundStatus = 'pending'
  let pending = await h.command('payment.refund', payload)
  assert.equal(pending.status, 'pending')
  assert.equal((await read(h, '/api/glove/balances')).invoices[0].due, '0.00')
  h.stripePayments.refunds.get(pending.providerReference).status = 'succeeded'
