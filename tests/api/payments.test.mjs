  await b.agent.run('payment.record', { invoiceId: inv.id, version: inv.version, method: 'cash', amount: '1.00', reference: 'synthetic-glove-10' }, { error: 'FORBIDDEN' })
  await assertTrail(h, ['refund.unconfirmed'])
