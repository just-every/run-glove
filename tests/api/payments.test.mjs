test('PAY-002 rejects invalid callbacks and unauthorized requests without effects, fences reconnects and never retries an uncertain Checkout', async t => {
  const h = await installation(); t.after(() => h.close())
  for (const query of ['?result=submitted', '?result=cancelled', '?result=%3Cscript%3E']) {
    const returned = await h.request('/payment-return' + query, { as: '' })
    assert.equal(returned.status, 200)
    const html = await returned.text()
    assert.match(html, /This page does not confirm a payment/)
    assert.doesNotMatch(html, /<script>|synthetic-glove-|Harbourview/)
    assert.match(returned.headers.get('cache-control'), /no-store/)
  }
  assert.equal((await h.request('/payment-return', { as: '', method: 'POST' })).status, 405)
  const b = await business(h, { currency: 'USD' })
  const inv = await paidInvoice(h, b, '2026-10-20')
  await b.office.run('payment.connect', {}, { error: 'FORBIDDEN' })
  const disconnected = await h.state()
  const networkBefore = h.stripePayments.calls.length
  await h.command('payment.connect', { version: disconnected.business[0].version, mode: 'test', key: 'synthetic-glove-1\nsynthetic-glove-2', webhookSecret: 'synthetic-glove-2' }, { error: 'INPUT' })
  assert.equal(h.stripePayments.calls.length, networkBefore, 'malformed credentials never reach a provider or header diagnostic')
  h.stripePayments.livemode = true
  await h.command('payment.connect', { version: disconnected.business[0].version, mode: 'test', key: 'synthetic-glove-1', webhookSecret: 'synthetic-glove-2' }, { error: 'PAYMENT_MODE' })
  assert.deepEqual(await h.state(), disconnected, 'a live key cannot create even a test-labeled connection')
  assert.equal(h.stripePayments.sessions.length, 0)
  h.stripePayments.livemode = false
  await connectPayments(h)
  await b.office.run('payment.checkout', { invoiceId: inv.id, version: inv.version, method: 'card' }, { error: 'FORBIDDEN' })
  await h.command('payment.checkout', { invoiceId: inv.id, version: inv.version - 1, method: 'card' }, { error: 'STALE' })
  await h.command('payment.checkout', { invoiceId: inv.id, version: inv.version, method: 'card', tip: '99.00' }, { error: 'INPUT' })
  await h.command('payment.checkout', { invoiceId: inv.id, version: inv.version, method: 'card', cardNumber: 'synthetic-glove-5' }, { error: 'INPUT' })
  const checkout = await h.command('payment.checkout', { invoiceId: inv.id, version: inv.version, method: 'card' })
  const pi = h.stripePayments.intents.get(h.stripePayments.sessions[0].intentId)
  const before = await h.state(), calls = h.stripePayments.calls.length
  assert.equal((await paymentEvent(h, pi, 'payment_intent.succeeded', { signature: false })).status, 401)
  assert.equal((await paymentEvent(h, pi, 'payment_intent.succeeded', { at: 1 })).status, 401)
  assert.equal(h.stripePayments.calls.length, calls, 'unauthenticated callbacks make no provider call')
  assert.deepEqual(await h.state(), before, 'invalid callbacks write no product fact')
  pi.amount++
  assert.equal((await paymentEvent(h, pi, 'payment_intent.succeeded')).status, 401)
  assert.deepEqual(await h.state(), before)
  pi.amount--; pi.livemode = true
  assert.equal((await paymentEvent(h, pi, 'payment_intent.succeeded')).status, 401)
  pi.livemode = false
  await h.command('payment.checkout', { invoiceId: inv.id, version: inv.version, method: 'card' }, { error: 'PAYMENT_PENDING' })
  Object.assign(pi, { status: 'requires_payment_method', latest_charge: { id: 'synthetic-glove-declined', status: 'failed' } })
  assert.equal((await paymentEvent(h, pi, 'payment_intent.payment_failed')).status, 200)
  assert.equal((await h.state()).payments.find(p => p.id === checkout.id).status, 'failed')
  await h.command('payment.checkout', { invoiceId: inv.id, version: inv.version, method: 'card' }, { error: 'PAYMENT_PENDING' })
  await connectPayments(h)
  assert.equal((await paymentEvent(h, pi, 'payment_intent.succeeded')).status, 200)
  assert.equal((await h.state()).payments.find(p => p.id === checkout.id).status, 'failed', 'old connection cannot mutate new funds')
  const next = await paidInvoice(h, b, '2026-10-21'), commandId = randomUUID(), payload = { invoiceId: next.id, version: next.version, method: 'card' }
  h.stripePayments.status = 503
  const uncertain = await h.command('payment.checkout', payload, { commandId })
  assert.equal(uncertain.checkoutUrl, undefined)
  const attempted = h.stripePayments.calls.length
  await h.command('payment.checkout', payload, { commandId })
  assert.equal(h.stripePayments.calls.length, attempted, 'a replay recovers reservation without repeating provider attempt')
  await assertTrail(h, ['payment.checkoutUnconfirmed'])
  const fresh = await paidInvoice(h, b, '2026-10-22')
  // A restored installation retains business/payment records but has no private provider binding.
  await h.db.prepare("DELETE FROM glove_provider_keys WHERE provider='stripe-payments'").run()
  const withoutKey = await h.state(), requestsBefore = h.stripePayments.calls.length
  await h.command('payment.checkout', { invoiceId: fresh.id, version: fresh.version, method: 'card' }, { error: 'PAYMENT_SETUP' })
  assert.deepEqual(await h.state(), withoutKey, 'missing private binding cannot strand a new reservation')
  assert.equal(h.stripePayments.calls.length, requestsBefore)
})


test('PAY-002 payment custody follows customer merge and undo and erasure preserves anonymous financial effects', async t => {
  const h = await installation(); t.after(() => h.close())
  const b = await business(h, { currency: 'USD' })
  const inv = await paidInvoice(h, b, '2026-10-20')
  await connectPayments(h)
  const p = await h.command('payment.checkout', { invoiceId: inv.id, version: inv.version, method: 'card' })
  const pi = h.stripePayments.intents.get(h.stripePayments.sessions[0].intentId)
  Object.assign(pi, { status: 'succeeded', amount_received: pi.amount, latest_charge: { id: 'synthetic-glove-custody-charge', created: Math.floor(Date.now() / 1000), status: 'succeeded', balance_transaction: { fee: 60 } } })
  assert.equal((await paymentEvent(h, pi, 'payment_intent.succeeded')).status, 200)
  const survivor = await h.command('customer.save', { name: 'Surviving customer', email: 'survivor@example.test' })
  let s = await h.state()
  const merged = await h.command('customer.merge', { survivorId: survivor.id, mergedIds: [b.customer.id], versions: { [survivor.id]: survivor.version, [b.customer.id]: s.customers.find(c => c.id === b.customer.id).version } })
  assert.ok(merged.moved.some(m => m.kind === 'payments' && m.id === p.id))
  assert.equal((await h.state()).payments.find(x => x.id === p.id).customerId, survivor.id)
  await h.command('customer.unmerge', { mergeId: merged.id, version: merged.version })
  s = await h.state()
  assert.equal(s.payments.find(x => x.id === p.id).customerId, b.customer.id)
  const customer = s.customers.find(c => c.id === b.customer.id)
  const preview = await h.command('privacy.preview', { customerId: customer.id, version: customer.version })
  await h.command('privacy.erase', { customerId: customer.id, version: customer.version, confirm: 'ERASE', fingerprint: preview.fingerprint })
  s = await h.state()
  const anonymous = s.payments.find(x => x.id === p.id)
  assert.equal(anonymous.amount, p.amount)
  assert.ok(anonymous.erasedAt)
  assert.equal(anonymous.intentId, undefined)
  assert.equal(anonymous.providerReference, undefined)
  assert.equal((await h.db.prepare('SELECT COUNT(*) AS n FROM glove_payment_attempts WHERE payment_id=?').bind(p.id).first()).n, 0)
  assert.equal((await read(h, '/api/glove/dashboard')).paidToday.total, p.amount)
  assert.deepEqual((await read(h, '/api/glove/reports/receivables.json?asOf=2099-01-01')).customers, [])
  const exported = await read(h, '/api/glove/export')
  assert.doesNotMatch(JSON.stringify(exported), /synthetic-glove-intent|synthetic-glove-custody-charge|accounts@harbourview\.example/)
})

