import test from 'node:test'
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { installation, assertTrail } from './harness.mjs'
import { readinessFixture } from '../fixtures/readiness.mjs'

test('Readiness five-visit preparation lifecycle preserves allocation, receipts, inert source-linked fixes and personal-data custody', async t => {
  const h = await installation({ at: '2029-12-31T12:00:00Z' }); t.after(() => h.close())
  const f = await readinessFixture(h)
  const recurring = await h.command('job.create', { customerId: f.customers[0].id, siteId: f.sites[0].id, title: 'Later recurring work' })
  await h.command('series.create', { jobId: recurring.id, version: recurring.version, technicianId: f.tech.id, rule: { unit: 'week', interval: 1 }, date: '2030-01-08', start: '15:00', end: '16:00', horizonDays: 7 })
  await h.request('/__test/clock', { method: 'POST', body: { at: '2030-01-01T12:00:00Z' } })
  const before = await h.state(), sent = [h.mails.length, h.email.sent.length, h.twilio.calls.length]
  let { body: board } = await f.board()
  assert.deepEqual(board.rows.map(r => r.visitId), f.visits.map(v => v.id))
  assert.deepEqual(board.rows.map(r => [r.parts[0].needed, r.parts[0].onVan, r.parts[0].onBoard]), [['1', '3', true], ['1', '3', true], ['1', '3', true], ['1', '3', false], ['1', '3', false]])
  assert.deepEqual(board.rows.map(r => [r.parts[0].allocatedThrough, r.parts[0].remainingAfter]), [['1', '2'], ['2', '1'], ['3', '0'], ['4', '-1'], ['5', '-2']])
  assert.deepEqual(board.rows.map(r => [r.partsStatus, r.access, r.overall]), [['allocated on van', 'unknown', 'unconfirmed'], ['allocated on van', 'unknown', 'unconfirmed'], ['allocated on van', 'unknown', 'unconfirmed'], ['missing parts', 'unknown', 'unconfirmed'], ['missing parts', 'unknown', 'unconfirmed']])
  assert.deepEqual(board.rows[4].orders.map(o => [o.id, o.lines[0].ordered, o.lines[0].received, o.receipts.length]), [[f.po.id, '2', '1', 1]])
  assert.equal(board.rows[4].orderStatus, 'unreceived order')
  assert.deepEqual(board.proposals, [
    { kind: 'parts', title: 'Allocate missing parts', sources: [3, 4].map(i => ({ visitId: f.visits[i].id, jobId: f.jobs[i].id, stockId: f.van.id, serviceIds: [f.material.id] })) },
    { kind: 'receipt', title: 'Verify outstanding receipts', sources: [{ visitId: f.visits[4].id, jobId: f.jobs[4].id, orderIds: [f.po.id] }] },
    { kind: 'access', title: 'Verify customer access', sources: [0, 1, 2, 3, 4].map(i => ({ visitId: f.visits[i].id, jobId: f.jobs[i].id, siteId: f.sites[i].id })) },
  ])
  const initial = board
  const preparationFingerprint = board.fingerprint
  const commandId = randomUUID(), prepared = await f.prepare(board, { commandId })
  assert.equal(prepared.reviews.length, 5)
  assert.deepEqual(prepared.reviews.map(r => r.proposals.map(p => p.kind)), [['access'], ['access'], ['access'], ['parts', 'access'], ['parts', 'receipt', 'access']])
  assert.deepEqual(await f.prepare(board, { commandId }), prepared)
  assert.deepEqual((await f.prepare(board)).reviews.map(r => [r.id, r.version]), prepared.reviews.map(r => [r.id, r.version]))
  assert.deepEqual((await f.board()).body.rows.map(r => r.preparation), ['current', 'current', 'current', 'current', 'current'])
  const after = await h.state()
  for (const kind of ['visits', 'jobs', 'stock', 'stockMoves', 'purchaseOrders', 'messages', 'payments', 'invoices', 'bookingOffers', 'quotes']) assert.deepEqual(after[kind], before[kind], `${kind} unchanged by inspection and preparation`)
  assert.deepEqual([h.mails.length, h.email.sent.length, h.twilio.calls.length], sent)
  f.po = await h.command('po.receive', { poId: f.po.id, version: f.po.version, lines: [{ lineId: f.po.lines[0].id, quantity: '1' }] })
  board = (await f.board()).body
  assert.equal(board.rows[4].orderStatus, 'received in full')
  assert.equal(board.rows[4].orders[0].receipts.length, 2)
  assert.equal(board.rows[4].partsStatus, 'missing parts', 'warehouse receipts do not place parts on the van')
  assert.equal(board.rows[4].preparation, 'stale')
  assert.deepEqual(board.proposals.map(p => p.kind), ['parts', 'access'])
  await h.command('stock.count', { locationId: f.van.id, serviceId: f.material.id, quantity: '5' })
  await f.prepare(initial, { error: 'STALE' })
  const current = (await f.board()).body
  assert.deepEqual(current.rows.map(r => r.parts[0].onBoard), [true, true, true, true, true])
  assert.deepEqual(current.rows.map(r => r.preparation), ['stale', 'stale', 'stale', 'stale', 'stale'])
  await f.prepare(current)
  assert.equal((await h.state()).readiness.length, 5)
  await f.field.run('readiness.prepare', { date: current.date, fingerprint: current.fingerprint }, { error: 'FORBIDDEN' })
  assert.equal((await f.board(f.field.cookie)).status, 403)
  assert.equal((await f.board('')).status, 401)
  const role = await h.command('role.save', { name: 'Readiness custom viewer', permissions: ['reports.read', 'export.read'] })
  const custom = await h.person('Readiness Custom', `custom:${role.id}`)
  await custom.run('readiness.prepare', { date: current.date, fingerprint: current.fingerprint }, { error: 'FORBIDDEN' })
  assert.equal((await f.board(custom.cookie)).status, 403)
  const token = await h.command('token.issue', { name: 'Readiness integration', role: 'dispatcher' })
  const tokenRead = await h.request(`/api/glove/readiness?date=${current.date}`, { as: '', headers: { authorization: `Bearer ${token.token}` } })
  assert.equal(tokenRead.status, 403)
  // Every retained projection follows the board's current readiness authority.
  const readinessEvents = events => events.filter(e => e.subjectKind === 'readiness' || e.subject_kind === 'readiness' || e.kind?.startsWith('readiness.'))
  const projections = async (options, allowed) => {
    const state = await h.request('/api/glove/state', options).then(r => { assert.equal(r.status, 200); return r.json() })
    assert.equal(state.readiness.length, allowed ? 5 : 0, 'state retained readiness')
    assert.equal(readinessEvents(state.events).length > 0, allowed, 'state readiness Activity')
    const activity = await h.request('/api/glove/activity', options).then(r => { assert.equal(r.status, 200); return r.json() })
    assert.equal(readinessEvents(activity.events).length > 0, allowed, 'paged readiness Activity')
    const timeline = await h.request(`/api/glove/jobs/${f.jobs[0].id}/timeline`, options).then(r => { assert.equal(r.status, 200); return r.json() })
    assert.equal(readinessEvents(timeline.events).length > 0, allowed, 'job readiness timeline')
    const conversation = await h.request(`/api/glove/conversation?jobId=${f.jobs[0].id}`, options).then(r => { assert.equal(r.status, 200); return r.json() })
    assert.equal(conversation.entries.some(e => e.channel === 'agent' && /readiness/.test(e.text)), allowed, 'readiness conversation')
    const history = await h.request(`/api/glove/sites/${f.sites[0].id}/history`, options).then(r => { assert.equal(r.status, 200); return r.json() })
    assert.equal(history.entries.some(e => /readiness/.test(e.label)), allowed, 'property readiness history')
    return state
  }
  const exportProjection = async (options, allowed) => {
    const exported = await h.request('/api/glove/export', options).then(r => { assert.equal(r.status, 200); return r.json() })
    assert.equal(exported.readiness.length, allowed ? 5 : 0, 'export retained readiness')
    assert.equal(readinessEvents(exported.timeline).length > 0, allowed, 'export readiness timeline')
    assert.equal(exported.timeline.some(e => JSON.parse(e.data || '{}').recordChanges?.some(r => r.kind === 'readiness')), allowed, 'export readiness changes')
  }
  const officeToken = await h.command('token.issue', { name: 'Readiness report integration', role: 'office' })
  const excluded = [{ as: custom.cookie }, { as: '', headers: { authorization: `Bearer ${officeToken.token}` } }]
  for (const options of excluded) {
    assert.equal((await h.request(`/api/glove/readiness?date=${current.date}`, options)).status, 403)
    await exportProjection(options, false)
    await projections(options, false)
  }
  const office = await h.person('Readiness Office', 'office')
  for (const options of [{}, { as: office.cookie }, { as: f.dispatcher.cookie }, { as: f.agent.cookie }]) await projections(options, true)
  await exportProjection({}, true)
  await exportProjection({ as: office.cookie }, true)
  await h.command('agents.pause', { paused: true })
  assert.equal((await f.board()).body.error.code, 'PAUSED')
  await f.prepare(initial, { commandId, error: 'PAUSED' })
  await projections({ as: f.agent.cookie }, false)
  await projections({ as: f.dispatcher.cookie }, true)
  await exportProjection({}, true)
  await h.command('agents.pause', { paused: false })
  await projections({ as: f.agent.cookie }, true)
  await h.command('role.set', { operatorId: f.agent.id, role: 'viewer' })
  await f.prepare(initial, { commandId, error: 'FORBIDDEN' })
  await h.command('role.set', { operatorId: f.agent.id, role: 'agent' })
  const branch = await h.command('branch.save', { name: 'Other branch', prefix: 'OTHER', timezone: 'America/Chicago', zips: [] })
  await h.command('branch.limit', { operatorId: f.agent.id, branchId: branch.id })
  assert.deepEqual((await f.board()).body.rows, [])
  assert.deepEqual((await f.board()).body.proposals, [])
  await f.prepare((await f.board()).body, { error: 'NOT_FOUND' })
  const customer = await h.command('customer.save', { name: 'Branch peer', branchId: branch.id })
  const site = await h.command('site.save', { customerId: customer.id, address: '40 Branch Street', branchId: branch.id })
  const tech = await h.command('technician.save', { name: 'Branch technician', branchId: branch.id })
  const job = await h.command('job.create', { customerId: customer.id, siteId: site.id, title: 'Branch work' })
  const visit = await h.command('visit.book', { jobId: job.id, technicianId: tech.id, date: '2030-01-02', start: '10:00', end: '11:00' })
  assert.deepEqual((await f.board()).body.rows.map(r => r.visitId), [visit.id])
  assert.deepEqual((await f.board()).body.proposals.flatMap(p => p.sources).map(s => s.jobId), [job.id])
  await f.prepare(initial, { commandId, error: 'NOT_FOUND' })
  await f.prepare(initial, { error: 'STALE' })
  assert.deepEqual((await f.agent.state()).readiness, [])
  await h.command('branch.limit', { operatorId: f.agent.id, branchId: null })
  await assertTrail(h, ['readiness.prepared'])
  const activity = await h.request('/api/glove/activity').then(r => r.json())
  const events = activity.events.filter(e => e.kind === 'readiness.prepared' && e.commandId === commandId)
  assert.equal(events.length, 5)
  assert.deepEqual(new Set(events.map(e => e.actorId)), new Set([f.agent.id]))
  assert.deepEqual(new Set(events.map(e => e.jobId)), new Set(f.jobs.map(j => j.id)))
  const exported = await h.request('/api/glove/export').then(r => r.json())
  assert.equal(exported.readiness.length, 5)
  const preview = await h.command('privacy.preview', { customerId: f.customers[4].id, version: f.customers[4].version })
  await h.command('privacy.erase', { customerId: f.customers[4].id, version: f.customers[4].version, fingerprint: preview.fingerprint, confirm: 'ERASE' })
  const state = await h.state()
  assert.deepEqual(state.readiness.map(r => r.visitId).sort(), f.visits.slice(0, 4).map(v => v.id).sort())
  const afterErasure = (await f.board()).body
  assert.deepEqual(afterErasure.rows.map(r => r.visitId).sort(), [...f.visits.slice(0, 4), visit].map(v => v.id).sort())
  assert.equal(afterErasure.proposals.flatMap(p => p.sources).some(s => s.jobId === f.jobs[4].id), false)
  const replay = await h.request('/api/glove/commands', { as: f.agent.cookie, method: 'POST', body: { commandId, type: 'readiness.prepare', payload: { date: board.date, fingerprint: preparationFingerprint } } }).then(r => r.json())
  assert.equal(replay.error.code, 'ERASED')
})
