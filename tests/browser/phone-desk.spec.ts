const postSms = async (h: any, request: Request) => h.mf.dispatchFetch(request.url, { method: request.method, headers: Object.fromEntries(request.headers), body: await request.text() })
const section = (page: import('@playwright/test').Page, name: string) => page.locator('section,form').filter({ has: page.getByRole('heading', { name, exact: true }) }).last()
test('The Owner runs the whole phone desk and Office repeats its permitted steps with exact role refusals at 390 and 1440', async ({ browser }) => {
  for (const width of [390, 1440]) {
    const h = await installation()
    const day = new Date().toISOString().slice(0, 10), fixed = `${day}T12:00:00Z`
    await h.request('/__test/clock', { method: 'POST', body: { at: fixed } })
    const b = await business(h, { currency: 'USD', timezone: 'UTC', address: '1400 West Main Street, Austin TX 78701' })
    await connectMail(h, 'postmark'); await connectPayments(h)
    let customer = await h.command('customer.save', { ...b.customer, phone: '+13125550123' })
    await h.command('sms.connect', { version: (await h.state()).business[0].version, provider: 'twilio', accountSid: h.twilio.accountSid, authToken: h.twilio.authToken, fromNumber: h.twilio.fromNumber, registration: 'a2p10dlc', registered: true, live: true })
    await h.command('sms.configure', { version: (await h.state()).business[0].version, enabled: true, approved: true })
    await h.command('sms.inboxConfigure', { version: (await h.state()).business[0].version, enabled: true, approved: true })
    await h.command('sms.consent', { customerId: customer.id, version: customer.version, purpose: 'visits', enabled: true, address: customer.phone, source: 'Customer asked on the booking call', wording: 'Please text me about my service visit. STOP ends texts.', timezone: 'UTC' })
    const card = await registerSavedCard(h, customer.id)
    const owner = await deskPage(browser, h, width)
    try {
      const page = owner.page; await page.clock.setFixedTime(new Date(fixed))
      await page.goto(`${origin}/app#quotes`)
      const request = section(page, 'Record a request')
      await request.getByLabel('Customer', { exact: true }).selectOption(customer.id)
      await request.getByLabel('Site', { exact: true }).selectOption(b.site.id)
      await request.getByLabel('What the customer needs', { exact: true }).fill('Phoned in: surgery air conditioner blowing warm air')
      await phoneScreen(page, width, 'owner-request', request)
      await action(page, request.getByRole('button', { name: 'Record request', exact: true }))
      await page.getByRole('button', { name: 'Quote it', exact: true }).click()
      const draft = section(page, `Quote for ${customer.name}`)
      await draft.getByLabel('Title', { exact: true }).fill('Surgery air conditioner service')
      await draft.getByLabel('Site', { exact: true }).selectOption(b.site.id)
      await draft.getByLabel('From the price book', { exact: true }).selectOption(b.service.id)
      const quoteDraft = await action(page, draft.getByRole('button', { name: 'Save draft', exact: true }))
      await action(page, page.getByRole('button', { name: /^Approve revision 1 at/ }))
      const quoteEmail = page.getByRole('region', { name: `Email ${quoteDraft.number}`, exact: true })
      await action(page, quoteEmail.getByRole('button', { name: 'Email quote', exact: true }))
      expect(h.email.sent.at(-1).to).toBe(customer.email)
      await phoneScreen(page, width, 'owner-quote-sent', quoteEmail)
      await action(page, page.getByRole('button', { name: 'Record acceptance', exact: true }))
      await page.goto(`${origin}/app#dispatch`)
      const job = await action(page, page.getByRole('button', { name: 'Create job', exact: true }))
      const booking = page.getByRole('button', { name: 'Book a visit', exact: true })
      await booking.focus()
      await expect(page.getByRole('tooltip', { name: 'Book a visit', exact: true })).toBeVisible()
      await phoneScreen(page, width, 'owner-dispatch-tooltip', booking)
      await booking.click()
      const book = section(page, 'Book a visit')
      await book.getByLabel('Technician', { exact: true }).selectOption(b.priya.id)
      await book.getByLabel('Starts', { exact: true }).fill('13:00')
      await book.getByLabel('Ends', { exact: true }).fill('14:00')
      await action(page, book.getByRole('button', { name: 'Book visit', exact: true }))
      await phoneScreen(page, width, 'owner-booked')
      const visit = (await h.state()).visits.find((v: any) => v.jobId === job.id)
      await b.priyaPerson.run('visit.arrive', { visitId: visit.id, deviceTime: visit.startAt })
      for (const item of job.checklist.filter((i: any) => i.required)) await b.priyaPerson.run('visit.capture', { visitId: visit.id, deviceTime: visit.startAt, kind: 'checklist', itemId: item.id, result: 'done' })
      await b.priyaPerson.run('visit.complete', { visitId: visit.id, deviceTime: visit.endAt, summary: 'Cleaned coil and filters; cooling restored', signoff: { absentReason: 'Customer at work' } })
      await page.goto(`${origin}/app#invoices`)
      const invoice = await action(page, page.getByRole('button', { name: 'Prepare invoice', exact: true }))
      await page.getByRole('button', { name: invoice.number, exact: true }).click()
      await action(page, page.getByRole('button', { name: /^Approve revision 1 at/ }))
      const email = page.getByRole('region', { name: `Email ${invoice.number}`, exact: true })
      await action(page, email.getByRole('button', { name: 'Email invoice', exact: true }))
      await phoneScreen(page, width, 'owner-invoice-sent', email)
      const payments = page.getByRole('region', { name: 'Payments and balance', exact: true })
      await payments.getByLabel('Payment amount', { exact: true }).fill(invoice.revisions[0].totals.total)
      await payments.getByLabel('Receipt or check reference', { exact: true }).fill('Check 1842')
      await action(page, payments.getByRole('button', { name: 'Record payment', exact: true }))
      await expect(payments).toContainText('Amount due $0.00')
      await phoneScreen(page, width, 'owner-check-paid', payments)
      const second = await paidInvoice(h, b, new Date(Date.parse(`${day}T12:00:00Z`) + 86400000).toISOString().slice(0, 10))
      await page.goto(`${origin}/app#invoices/${second.id}`)
      const charge = page.getByRole('form', { name: 'Charge saved card', exact: true })
      await charge.getByLabel('Saved card', { exact: true }).selectOption(card.id)
      await charge.getByLabel('Saved-card charge amount', { exact: true }).fill(second.revisions[0].totals.total)
      await charge.getByRole('checkbox').check()
      const payment = await action(page, charge.getByRole('button', { name: 'Charge saved card', exact: true }))
      await phoneScreen(page, width, 'owner-card-pending', charge)
      expect((await h.state()).payments.find((p: any) => p.id === payment.id).effects).toEqual([])
      expect((await confirmSavedCard(h, payment.id)).status).toBe(200)
      await page.reload()
      await expect(page.getByRole('region', { name: 'Payments and balance', exact: true })).toContainText('Amount due $0.00')
      await phoneScreen(page, width, 'owner-card-paid')
      expect((await postSms(h, h.twilio.inbound(h.origin, customer.phone, 'Can you call reception before arriving?'))).status).toBe(200)
      await page.goto(`${origin}/app#inbox`)
      await page.getByRole('button', { name: customer.name, exact: true }).click()
      const thread = page.getByRole('region', { name: 'Text conversation', exact: true })
      await expect(thread).toContainText('Can you call reception before arriving?')
      await action(page, thread.getByRole('button', { name: 'Take conversation', exact: true }))
      await thread.getByLabel('Related job', { exact: true }).selectOption(job.id)
      await action(page, thread.getByRole('button', { name: 'Link job', exact: true }))
      await thread.getByLabel('Reply template', { exact: true }).selectOption('Thank you. The office will call you to confirm the details.')
      await action(page, thread.getByRole('button', { name: 'Send text reply', exact: true }))
      await expect(thread).toContainText('Accepted by Twilio')
      expect([...h.twilio.messages.values()].at(-1).body).toContain('The office will call')
      await phoneScreen(page, width, 'owner-text-reply', thread)
      await page.goto(`${origin}/app#today`)
      await expect(page.getByRole('heading', { name: 'Today', exact: true })).toBeVisible()
      await phoneScreen(page, width, 'owner-dashboard')
      await officePhone(browser, h, b, width, fixed, second, job)
    } finally { await owner.context.close(); await h.close() }
  }
})

async function officePhone(browser: import('@playwright/test').Browser, h: any, b: any, width: number, fixed: string, invoice: any, job: any) {
  const { context, page } = await deskPage(browser, h, width, b.office.cookie)
  try {
    await page.clock.setFixedTime(new Date(fixed))
    const refuse = async (type: string, payload: object) => {
      const result = await page.evaluate(async ({ type, payload }) => (await fetch('/api/glove/commands', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ commandId: crypto.randomUUID(), type, payload }) })).json(), { type, payload })
      expect(result.error?.code).toBe('FORBIDDEN')
    }
    await page.goto(`${origin}/app#quotes`)
    const request = section(page, 'Record a request')
    await request.getByLabel('Customer', { exact: true }).selectOption(b.customer.id)
    await request.getByLabel('Site', { exact: true }).selectOption(b.site.id)
    await request.getByLabel('What the customer needs', { exact: true }).fill('Office phone request: filter replacement')
    await action(page, request.getByRole('button', { name: 'Record request', exact: true }))
    await expect(page.getByRole('button', { name: 'Quote it', exact: true })).toHaveCount(0)
    await refuse('quote.draft', { customerId: b.customer.id, siteId: b.site.id })
    await refuse('quote.approve', { quoteId: job.quoteId })
    await refuse('quote.accept', { quoteId: job.quoteId })
    await phoneScreen(page, width, 'office-request-and-quote-refusal', request)
    const quote = (await h.state()).quotes.find((q: any) => q.id === job.quoteId)
    const q = await h.command('quote.draft', { customerId: b.customer.id, siteId: b.site.id, title: 'Office send', lines: [{ description: 'Filter service', quantity: '1', unitPrice: '100.00', tax: 'FREE' }] })
    await h.command('quote.approve', { quoteId: q.id, version: q.version, revision: 1 })
    await page.reload()
    await page.getByRole('button', { name: `${q.number} · Office send`, exact: true }).click()
    await action(page, page.getByRole('region', { name: `Email ${q.number}`, exact: true }).getByRole('button', { name: 'Email quote', exact: true }))
    await phoneScreen(page, width, 'office-quote-sent')
    await page.goto(`${origin}/app#dispatch`)
    await refuse('job.create', { quoteId: quote.id })
    await refuse('visit.book', { jobId: job.id, technicianId: b.priya.id, date: fixed.slice(0, 10), start: '16:00', end: '17:00' })
    await refuse('visit.change', { visitId: (await h.state()).visits.find((v: any) => v.jobId === job.id).id })
    await phoneScreen(page, width, 'office-booking-refused')
    const date = new Date(Date.parse(fixed) + 2 * 86400000).toISOString().slice(0, 10)
    const nextInvoice = await paidInvoice(h, b, date)
    await page.goto(`${origin}/app#invoices/${nextInvoice.id}`)
    await action(page, page.getByRole('region', { name: `Email ${nextInvoice.number}`, exact: true }).getByRole('button', { name: 'Email invoice', exact: true }))
    const payments = page.getByRole('region', { name: 'Payments and balance', exact: true })
    await payments.getByLabel('Payment amount', { exact: true }).fill('20.00')
    await payments.getByLabel('Receipt or check reference', { exact: true }).fill('Office check 1843')
    await action(page, payments.getByRole('button', { name: 'Record payment', exact: true }))
    const charge = page.getByRole('form', { name: 'Charge saved card', exact: true }), card = (await h.state()).customers.find((c: any) => c.id === b.customer.id).savedCards[0]
    await charge.getByLabel('Saved card', { exact: true }).selectOption(card.id)
    await charge.getByLabel('Saved-card charge amount', { exact: true }).fill('10.00')
    await charge.getByRole('checkbox').check()
    const paid = await action(page, charge.getByRole('button', { name: 'Charge saved card', exact: true }))
    expect((await confirmSavedCard(h, paid.id)).status).toBe(200)
    await page.reload(); await phoneScreen(page, width, 'office-invoice-and-payments', payments)
    expect((await postSms(h, h.twilio.inbound(h.origin, '+13125550123', 'Please confirm the next visit.'))).status).toBe(200)
    await page.goto(`${origin}/app#inbox`)
    await page.locator('li').filter({ hasText: 'Please confirm the next visit.' }).getByRole('button', { name: b.customer.name, exact: true }).click()
    const thread = page.getByRole('region', { name: 'Text conversation', exact: true })
    await thread.getByLabel('Text reply', { exact: true }).fill('The office will call to confirm.')
    await action(page, thread.getByRole('button', { name: 'Send text reply', exact: true }))
    await phoneScreen(page, width, 'office-text-reply', thread)
    await page.goto(`${origin}/app#today`)
    await expect(page.getByText("Today is the owner's dashboard", { exact: true })).toBeVisible()
    const dashboard = await page.evaluate(async () => (await fetch('/api/glove/dashboard')).status)
    expect(dashboard).toBe(403)
    await phoneScreen(page, width, 'office-dashboard-refused')
  } finally { await context.close() }
}
