import { expect, type Page, type Locator } from '@playwright/test'
import { action } from './desk-fixture'

/** Continue the staged-invoice journey through the native Owner review door. */
export async function progressScopeJourney(page: Page, h: any, b: any, width: number, origin: string, screen: (page: Page, width: number, name: string, anchor: Locator) => Promise<void>) {
  const service = await h.command('service.save', { code: 'SCOPE-ADD', name: 'Additional installation', unitPrice: '50.00', tax: 'FREE', checklist: [] })
  let quote = await h.command('quote.draft', { customerId: b.customer.id, siteId: b.site.id, title: 'Signed staged installation', lines: [{ serviceId: service.id, description: 'Original installation', quantity: '1', unitPrice: '200.00', tax: 'FREE' }] })
  quote = await h.command('quote.approve', { quoteId: quote.id, version: quote.version, revision: 1 })
  quote = await h.command('quote.accept', { quoteId: quote.id, version: quote.version, revision: 1, method: 'phone', customerName: b.customer.name })
  const job = await h.command('job.create', { quoteId: quote.id })
  const visit = await b.dispatcher.run('visit.book', { jobId: job.id, technicianId: b.priya.id, date: '2026-10-30', start: '09:00', end: '10:00' })
  let stage = await b.office.run('invoice.prepare', { jobId: job.id, progress: { name: 'Initial installation', final: false }, lines: [{ description: 'Initial installation', quantity: '1', unitPrice: '60.00', tax: 'FREE' }] })
  stage = await b.office.run('invoice.approve', { invoiceId: stage.id, version: stage.version, revision: 1 })
  const before = structuredClone((await h.state()).invoices.find((i: any) => i.id === stage.id))
  const tech = (await h.state()).technicians.find((t: any) => t.id === b.priya.id)
  await h.command('fieldQuote.configure', { technicianId: tech.id, version: tech.version, enabled: true, minPercent: 100, maxPercent: 100 })
  let change = await b.priyaPerson.run('fieldQuote.draft', { visitId: visit.id, title: 'Customer signed extra outlet', changeOrder: true, options: [{ name: 'Extra outlet', lines: [{ serviceId: service.id, quantity: '1' }] }] })
  change = await h.command('quote.approve', { quoteId: change.id, version: change.version, revision: 1 })
  await h.command('quote.consent', { version: (await h.state()).business[0].version, text: 'synthetic-glove-104 accepted electronic signature disclosure for the signed additional work.', accept: true })
  const link = await h.command('quote.link', { quoteId: change.id, version: change.version })
  const post = (body: any) => h.request('/api/glove/public/quote', { as: '', method: 'POST', headers: { authorization: `Bearer ${link.token}` }, body })
  const choice = { optionId: 'option-1', addOnIds: [] }
  const selection = await (await post({ action: 'choose', choice })).json()
  const signed = await post({ action: 'approve', name: 'Mei Lin', capacity: 'Property owner', choice, documentHash: selection.documentHash, selectionHash: selection.selection.hash, consent: { version: selection.disclosure.version, hash: selection.disclosure.hash, affirmed: true }, signature: { kind: 'typed', text: 'Mei Lin' } })
  expect(signed.status).toBe(200)
  change = (await h.state()).quotes.find((q: any) => q.id === change.id)
  expect((await h.state()).jobs.find((j: any) => j.id === job.id).totals.total).toBe('200.00')

  await page.unrouteAll({ behavior: 'wait' })
  await page.route(`${origin}/api/glove/**`, async route => {
    const req = route.request(), url = new URL(req.url())
    const response = await h.request(url.pathname + url.search, { method: req.method(), ...(req.postData() ? { body: JSON.parse(req.postData()!) } : {}) })
    await route.fulfill({ status: response.status, headers: Object.fromEntries(response.headers), body: Buffer.from(await response.arrayBuffer()) })
  })
  await page.goto(`${origin}/app#invoices`)
  await page.reload()
  const form = page.getByRole('form', { name: 'Prepare progress invoice' })
  await form.getByLabel('Progress job', { exact: true }).selectOption(job.id)
  const review = page.getByRole('region', { name: 'Reconcile signed progress scope', exact: true })
  const apply = review.getByRole('button', { name: `Apply ${change.number} to future stages`, exact: true })
  await expect(apply).toBeDisabled()
  await expect(review).toContainText('contract $200.00 → $250.00')
  await expect(review).toContainText(stage.number)
  await review.getByRole('checkbox').check()
  await screen(page, width, 'signed-scope-review', review)
  await action(page, apply)
  await expect(review).toHaveCount(0)
  await expect(form).toContainText('Contract $250.00 · Remaining $190.00')
  expect((await h.state()).invoices.find((i: any) => i.id === stage.id)).toEqual(before)
  const amended = (await h.state()).jobs.find((j: any) => j.id === job.id)
  expect(amended.progressReconciliations).toHaveLength(1)
  expect(amended.progressReconciliations[0].newCap).toBe('250.00')
  await screen(page, width, 'signed-scope-applied', form)
  const deviceTime = '2026-10-30T10:00:00Z'
  await b.priyaPerson.run('visit.arrive', { visitId: visit.id, deviceTime })
  for (const item of amended.checklist.filter((i: any) => i.required)) await b.priyaPerson.run('visit.capture', { visitId: visit.id, deviceTime, kind: 'checklist', itemId: item.id, result: 'done' })
  await b.priyaPerson.run('visit.complete', { visitId: visit.id, deviceTime, summary: 'Signed scope complete', signoff: { absentReason: 'Customer away' } })
  await page.reload()
  await form.getByLabel('Progress job', { exact: true }).selectOption(job.id)
  await form.getByLabel('Stage name', { exact: true }).fill('Signed scope final')
  await form.getByLabel('Description', { exact: true }).fill('Remaining signed installation')
  await form.getByLabel('Unit price', { exact: true }).fill('190.00')
  await form.getByRole('checkbox', { name: 'Final stage', exact: true }).check()
  await action(page, form.getByRole('button', { name: 'Prepare stage draft', exact: true }))
  const final = (await h.state()).invoices.find((i: any) => i.jobId === job.id && i.id !== stage.id)
  await page.getByRole('button', { name: final.number, exact: true }).click()
  await action(page, page.getByRole('button', { name: 'Approve revision 1 at $190.00', exact: true }))
  const detail = page.getByRole('region', { name: `${final.number} · ${b.customer.name}`, exact: true })
  await expect(detail).toContainText('Signed scope final')
  await expect(detail).toContainText('contract $250.00')
  await screen(page, width, 'signed-scope-approved-final', detail.locator('p').first())
  expect((await h.state()).invoices.find((i: any) => i.id === stage.id)).toEqual(before)
}
